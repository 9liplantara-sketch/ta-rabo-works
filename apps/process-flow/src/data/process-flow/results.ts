export const PROCESS_RESULTS = [...SPECIFIC, ...GENERIC_RESULTS];

export const RESULT_MAP = new Map(PROCESS_RESULTS.map((r) => [r.id, r]));

export function getResult(id: string) {
  return RESULT_MAP.get(id);
}

export function getAlternativeResults(result: ProcessResult) {
  return result.alternativeResultIds
    .map((id) => RESULT_MAP.get(id))
    .filter(Boolean) as ProcessResult[];
}
